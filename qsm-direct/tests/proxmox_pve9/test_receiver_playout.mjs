import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync(new URL('../../integration/proxmox/pve9/direct_ui/qsm-direct-console.js', import.meta.url), 'utf8');
const begin = source.indexOf('    const applyReceiverPlayoutDelay =');
const end = source.indexOf('    const readConsoleSettings =', begin);
assert.ok(begin > 0 && end > begin);
const context = vm.createContext({});
vm.runInContext(source.slice(begin, end) + '\nglobalThis.apply = applyReceiverPlayoutDelay;', context);
const standard = { jitterBufferTarget: null, playoutDelayHint: null };
context.apply(standard, 120);
assert.equal(standard.jitterBufferTarget, 120);
assert.equal(standard.playoutDelayHint, null);
context.apply(standard, 0);
assert.equal(standard.jitterBufferTarget, 0);
const legacy = { playoutDelayHint: null };
context.apply(legacy, 120);
assert.equal(legacy.playoutDelayHint, 0.12);
const rejected = { set jitterBufferTarget(_) { throw new Error('unsupported'); }, playoutDelayHint: null };
context.apply(rejected, 80);
assert.equal(rejected.playoutDelayHint, 0.08);
context.apply(null, 0);
context.apply({}, 0);
assert.equal((source.match(/applyReceiverPlayoutDelay\(videoReceiver, settings.playoutDelayMs\)/g) || []).length, 2);
console.log('QSM_RECEIVER_PLAYOUT_OK');
